"""Our Italian translations: record them and flag the ones an upstream merge loses.

The Italian catalogue (lms/locale/it.po) mixes upstream's Crowdin strings with
ours, and a merge that takes upstream's file silently drops ours. We record every
pair that is new or different against the upstream base, and C7 reports the
recorded pairs that are missing or changed in the current catalogue.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

from scripts.customizations.checks import ERROR, Finding

PO_PATH = "lms/locale/it.po"
TRANSLATIONS_FILE = "docs/customizations/translations-it.toml"

Key = tuple[str, str]

_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\"}
_ESCAPE = re.compile(r"\\(.)")
_KEYWORD = re.compile(r'^(msgctxt|msgid|msgstr)(?:\[\d+\])?\s+(".*")\s*$')


def _unquote(quoted: str) -> str:
	return _ESCAPE.sub(lambda m: _ESCAPES.get(m.group(1), m.group(0)), quoted[1:-1])


def parse_po(text: str) -> dict[Key, str]:
	"""Map (msgctxt or "", msgid) to msgstr. Obsolete `#~` entries and the header are skipped."""
	entries: dict[Key, str] = {}
	fields: dict[str, str] = {}
	current: str | None = None

	def flush() -> None:
		if "msgid" in fields and fields["msgid"] != "":
			entries[(fields.get("msgctxt", ""), fields["msgid"])] = fields.get("msgstr", "")
		fields.clear()

	for line in text.splitlines():
		line = line.strip()
		if line.startswith("#~"):
			continue
		if not line:
			flush()
			current = None
			continue
		if line.startswith("#"):
			continue
		if line.startswith("msgid_plural"):
			current = None
			continue
		match = _KEYWORD.match(line)
		if match:
			keyword = match.group(1)
			if keyword == "msgctxt" and "msgid" in fields:
				flush()
			if keyword == "msgid" and "msgid" in fields:
				flush()
			current = keyword
			# Plural forms keep only the first msgstr.
			if keyword == "msgstr" and "msgstr" in fields:
				current = None
				continue
			fields[keyword] = _unquote(match.group(2))
		elif line.startswith('"') and current is not None:
			fields[current] += _unquote(line)
	flush()
	return entries


def our_translations(base_po: str | None, head_po: str) -> dict[Key, str]:
	"""Entries of head that are absent from the base or differ from it, never empty ones."""
	base = parse_po(base_po) if base_po else {}
	return {
		key: msgstr
		for key, msgstr in parse_po(head_po).items()
		if msgstr and base.get(key) != msgstr
	}


def check_translations(recorded: dict[Key, str], head_po: str) -> list[Finding]:
	"""C7: every recorded pair is still in the catalogue with the same msgstr."""
	head = parse_po(head_po)
	findings: list[Finding] = []
	for (msgctxt, msgid), msgstr in recorded.items():
		current = head.get((msgctxt, msgid))
		if current == msgstr:
			continue
		label = f"{msgid!r}" + (f" (contesto {msgctxt!r})" if msgctxt else "")
		what = "manca" if current is None else f"è cambiata in {current!r}"
		findings.append(
			Finding(
				"translations",
				"C7",
				ERROR,
				f"traduzione italiana nostra persa: {label}, registrata {msgstr!r}, ora {what}",
				file=PO_PATH,
				anchor=msgid,
			)
		)
	return findings


def _toml_string(value: str) -> str:
	out = []
	for char in value:
		if char == "\\":
			out.append("\\\\")
		elif char == '"':
			out.append('\\"')
		elif char == "\n":
			out.append("\\n")
		elif char == "\r":
			out.append("\\r")
		elif char == "\t":
			out.append("\\t")
		elif ord(char) < 0x20 or ord(char) == 0x7F:
			out.append(f"\\u{ord(char):04x}")
		else:
			out.append(char)
	return '"' + "".join(out) + '"'


def write_recorded(path: Path, base: str, pairs: dict[Key, str]) -> None:
	"""Write the record, sorted by (msgctxt, msgid) so reruns give identical bytes."""
	lines = [
		"# Generated by scripts/customization_translations.py --write. Do not edit by hand.",
		f"generated_from = {_toml_string(base)}",
		"",
	]
	for (msgctxt, msgid), msgstr in sorted(pairs.items()):
		lines.append("[[translations]]")
		if msgctxt:
			lines.append(f"msgctxt = {_toml_string(msgctxt)}")
		lines.append(f"msgid = {_toml_string(msgid)}")
		lines.append(f"msgstr = {_toml_string(msgstr)}")
		lines.append("")
	Path(path).write_text("\n".join(lines), encoding="utf-8")


def read_recorded(path: Path) -> tuple[str, dict[Key, str]]:
	"""The base tag and the recorded pairs. Raises OSError or ValueError on a bad file."""
	try:
		raw = tomllib.loads(Path(path).read_text(encoding="utf-8"))
		pairs = {
			(item.get("msgctxt", ""), item["msgid"]): item["msgstr"]
			for item in raw.get("translations", [])
		}
		return raw["generated_from"], pairs
	except (tomllib.TOMLDecodeError, KeyError, TypeError, AttributeError) as exc:
		raise ValueError(f"{path}: {exc}") from exc
